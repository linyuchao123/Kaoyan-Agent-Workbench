-- v0.8: model observability without storing prompts, responses or secrets.
create table public.agent_model_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  thread_id uuid not null references public.agent_threads(id) on delete cascade,
  model_profile text not null check (model_profile in ('flash', 'pro')),
  provider text not null,
  model text not null,
  fallback_used boolean not null default false,
  status text not null check (status in ('success', 'degraded', 'error')),
  error_type text,
  latency_ms integer not null check (latency_ms >= 0),
  input_tokens integer not null default 0 check (input_tokens >= 0),
  output_tokens integer not null default 0 check (output_tokens >= 0),
  created_at timestamptz not null default now()
);

create index agent_model_usage_owner_time_idx
on public.agent_model_usage(user_id, created_at desc);

alter table public.agent_model_usage enable row level security;

create policy agent_model_usage_owner_select
on public.agent_model_usage for select to authenticated
using (user_id = auth.uid());

grant select on public.agent_model_usage to authenticated;

create or replace function public.record_agent_model_usage(
  requested_thread_id uuid,
  requested_model_profile text,
  requested_provider text,
  requested_model text,
  requested_fallback_used boolean,
  requested_status text,
  requested_latency_ms integer,
  requested_input_tokens integer,
  requested_output_tokens integer,
  requested_error_type text default null
)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  owner_id uuid := auth.uid();
begin
  if owner_id is null then
    raise exception 'authentication required';
  end if;
  if not exists (
    select 1 from public.agent_threads
    where id = requested_thread_id and user_id = owner_id
  ) then
    raise exception 'agent thread not found';
  end if;

  insert into public.agent_model_usage (
    user_id, thread_id, model_profile, provider, model, fallback_used, status,
    error_type, latency_ms, input_tokens, output_tokens
  ) values (
    owner_id,
    requested_thread_id,
    requested_model_profile,
    left(requested_provider, 80),
    left(requested_model, 160),
    requested_fallback_used,
    requested_status,
    nullif(left(coalesce(requested_error_type, ''), 120), ''),
    greatest(requested_latency_ms, 0),
    greatest(requested_input_tokens, 0),
    greatest(requested_output_tokens, 0)
  );
end;
$$;

revoke all on function public.record_agent_model_usage(
  uuid, text, text, text, boolean, text, integer, integer, integer, text
) from public;
grant execute on function public.record_agent_model_usage(
  uuid, text, text, text, boolean, text, integer, integer, integer, text
) to authenticated;
